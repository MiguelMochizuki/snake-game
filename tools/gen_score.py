"""
gen_score.py
Author: Miguel Mochizuki Silva
Description: Writes src/audio/score_data.cpp (the game's soundtrack) from the Mutopia Project MIDI of
Gounod's "Ave Maria" over Bach's Prelude in C major (BWV 846), piano and violin edition.
Source (public domain, typeset from Heugel 1856 by Yann Leprince):
https://www.mutopiaproject.org/ftp/GounodC/AveMaria-PianoViolin/AveMaria-PianoViolin.mid
Usage: python3 tools/gen_score.py AveMaria-PianoViolin.mid [--out src/audio/score_data.cpp]
"""
import argparse
import os
import struct


def read_vlq(data, i):
    """Reads a MIDI variable-length quantity; returns (value, next index)."""
    value = 0
    while True:
        b = data[i]
        i += 1
        value = (value << 7) | (b & 0x7F)
        if not b & 0x80:
            return value, i


def parse_midi(path):
    """Returns (ticks per quarter note, tracks), each track a list of (tick, status, args)."""
    data = open(path, "rb").read()
    _, _, _, count, division = struct.unpack(">4sIHHH", data[:14])
    i, tracks = 14, []
    for _ in range(count):
        _, length = struct.unpack(">4sI", data[i:i + 8])
        i += 8
        end, tick, running, events = i + length, 0, 0, []
        while i < end:
            delta, i = read_vlq(data, i)
            tick += delta
            b = data[i]
            if b == 0xFF:
                size, j = read_vlq(data, i + 2)
                i = j + size
                continue
            if b in (0xF0, 0xF7):
                size, j = read_vlq(data, i + 1)
                i = j + size
                continue
            if b & 0x80:
                running = b
                i += 1
            kind = running & 0xF0
            if kind in (0xC0, 0xD0):
                args, i = (data[i],), i + 1
            else:
                args, i = (data[i], data[i + 1]), i + 2
            events.append((tick, kind, args))
        tracks.append(events)
    return division, tracks


def notes_of(track):
    """Returns the notes of a track as sorted (start tick, end tick, pitch)."""
    on, notes = {}, []
    for tick, kind, args in track:
        if kind == 0x90 and args[1] > 0:
            on[args[0]] = tick
        elif kind == 0x80 or (kind == 0x90 and args[1] == 0):
            if args[0] in on:
                notes.append((on.pop(args[0]), tick, args[0]))
    return sorted(notes)


def main():
    """Builds the accompaniment table, the melody and the final chord, and writes the C++ file."""
    ap = argparse.ArgumentParser()
    ap.add_argument("midi")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "src", "audio", "score_data.cpp"))
    args = ap.parse_args()
    division, tracks = parse_midi(args.midi)
    sixteenth = division // 4

    arpeggio, final = {}, []
    for track in (2, 3):  # the two piano hands
        for start, _, pitch in notes_of(tracks[track]):
            step = start // sixteenth
            arpeggio.setdefault(step, []).append(pitch)
    steps = max(arpeggio)
    final = sorted(arpeggio.pop(steps))
    assert all(len(arpeggio[s]) == 1 for s in range(steps)), "accompaniment must be one note per sixteenth"
    table = [arpeggio[s][0] for s in range(steps)]
    melody = [(s // sixteenth, (e - s) // sixteenth, p) for s, e, p in notes_of(tracks[1])]

    lines = [
        "/**",
        " * score_data.cpp",
        " * Author: Miguel Mochizuki Silva",
        " * Description: The soundtrack. Generated by tools/gen_score.py, do not edit by hand.",
        " *",
        " * Charles Gounod's \"Ave Maria\" (1853) over J. S. Bach's Prelude in C major (BWV 846), both in the",
        " * public domain. Notes taken from the Mutopia Project edition typeset by Yann Leprince from the",
        " * Heugel 1856 score, which he placed in the public domain.",
        " */",
        '#include "snake_game/audio/score.hpp"',
        "",
        "// Accompaniment: one MIDI note per sixteenth, %d sixteenths" % steps,
        "const unsigned char ARPEGGIO_DATA[ARPEGGIO_STEPS] = {",
    ]
    for i in range(0, steps, 16):
        lines.append("\t" + ", ".join(str(n) for n in table[i:i + 16]) + ",")
    lines += ["};", "", "// The chord that ends the piece", "const int FINAL_CHORD[FINAL_CHORD_SIZE] = {" + ", ".join(map(str, final)) + "};", "",
              "// Melody: start sixteenth, length in sixteenths, MIDI note", "const MelodyNote MELODY[MELODY_COUNT] = {"]
    for i in range(0, len(melody), 4):
        lines.append("\t" + " ".join("{%d, %d, %d}," % m for m in melody[i:i + 4]))
    lines.append("};")
    open(args.out, "w").write("\n".join(lines) + "\n")
    print("steps", steps, "final chord", final, "melody notes", len(melody), "melody ends at step", melody[-1][0] + melody[-1][1])


if __name__ == "__main__":
    main()
